#!/usr/bin/env python3
import argparse
import struct


def z(value: str) -> bytes:
    raw = value.encode() + b"\x00"
    return struct.pack("<I", len(raw)) + raw


parser = argparse.ArgumentParser(description="Pack COFFLoader arguments for cdptk_bof.o")
parser.add_argument("command")
parser.add_argument("--port", type=int, default=9222)
parser.add_argument("--arg1", default="")
parser.add_argument("--arg2", default="")
parser.add_argument("--flags", type=int, default=0)
args = parser.parse_args()

payload = z(args.command) + struct.pack("<I", args.port) + z(args.arg1) + z(args.arg2) + struct.pack("<I", args.flags)
# COFFLoader expects the same little-endian packed layout generated by
# TrustedSec's beacon_generate.py, including the leading payload length.
print((struct.pack("<I", len(payload)) + payload).hex())
